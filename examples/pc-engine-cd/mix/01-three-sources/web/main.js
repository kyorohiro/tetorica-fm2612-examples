import {Playground} from 'tetorica-fm2612/playground_runtime.js';
import {runtimeAssetUrl} from 'tetorica-fm2612/package_assets.js';
import {encodeWav} from 'tetorica-fm2612/wav.js';

const playButton = document.getElementById('play');
const stopButton = document.getElementById('stop');
const executionSelect = document.getElementById('execution');
const editor = document.getElementById('code');
const status = document.getElementById('status');
const detail = document.getElementById('detail');
let activeRun = null;

// Generate the complete demo WAV before playback; never request PCM from the UI per block.
// Each track gets its own 25 ms fade. No external disc or sample data is used.
function makeDemoWav() {
  const sampleRate = 44100, seconds = 6, frames = Math.round(sampleRate * seconds);
  const left = new Float32Array(frames), right = new Float32Array(frames);
  for (let i = 0; i < frames; i++) {
    const t = i / sampleRate;
    const fade = Math.min(1, t / 0.025, (frames - 1 - i) / sampleRate / 0.025);
    left[i] = Math.sin(2 * Math.PI * 220 * t) * 0.08 * fade;
    right[i] = Math.sin(2 * Math.PI * 330 * t) * 0.08 * fade;
  }
  return new Uint8Array(encodeWav({left, right, sampleRate}));
}

// pce / adpcm / cdda / sleep belong to this loaded Playground script.
editor.value = `// Original generated audio, no disc, BIOS or game samples.
pce.initialize();
pce.setWaveform(0, Array.from({length: 32}, (_, i) =>
  Math.round(15.5 + 15.5 * Math.sin(2 * Math.PI * i / 32))));
pce.setVolume(0, 26);
pce.setPan(0, 15, 15);
await cdda.load('/generated/bed.wav'); // 44.1 kHz stereo PCM16, generated by the host.
const sampleRate = 8000, mono = new Float32Array(4000);
for (let i = 0; i < mono.length; i++) {
  const t = i / sampleRate;
  const fade = Math.min(1, t / 0.025, (mono.length - 1 - i) / sampleRate / 0.025);
  mono[i] = Math.sin(2 * Math.PI * 880 * t) * 0.16 * fade;
}
await adpcm.loadSample({sampleRate, channels: [mono]}, {rate: 12});
// Explicit demonstration trims, each applied once. These are not new defaults.
await mixer.set(pce.id, {volume: 0.44, pan: 0.2});
await mixer.set('msm5205', {volume: 0.7, pan: -0.3, muted: true});
await mixer.set('cdda', {volume: 1, pan: 0, muted: false});
await cdda.play();
await adpcm.play({loop: true}); // Muted ADPCM still advances on the audio clock.
console.log('PHASE_MIX_CDDA', await cdda.getState());
await sleep(1);
await mixer.set('cdda', {muted: true});
pce.noteOn(0, 'A4');
console.log('PHASE_MIX_PSG');
await sleep(1);
pce.allNotesOff();
await mixer.set('msm5205', {muted: false});
console.log('PHASE_MIX_ADPCM', await adpcm.getState());
await sleep(1);
await mixer.set('cdda', {muted: false});
console.log('PHASE_MIX_ALL');
for (const note of ['A4', 'C5', 'E5', 'A5']) {
  pce.noteOn(0, note);
  await sleep(0.5);
}
pce.allNotesOff();
await adpcm.stop();
await cdda.stop();
console.log('PHASE_MIX_STOP');
await sleep(0.8); // Drain Worker PSG lookahead before closing the audio context.`;

function report(run, message) {
  if (activeRun !== run) return;
  run.messages.push(String(message).slice(0, 500));
  if (run.messages.length > 16) run.messages.shift();
  detail.textContent = run.messages.join('\n');
}

playButton.addEventListener('click', async () => {
  if (activeRun) return;
  const run = {controller: new AbortController(), runtime: null, messages: []};
  activeRun = run;
  const {signal} = run.controller;
  const source = editor.value; // Edits take effect on the next Play.
  const execution = executionSelect.value;
  let result = 'Finished.';
  playButton.disabled = true;
  stopButton.disabled = false;
  executionSelect.disabled = true;
  status.textContent = 'Loading…';
  report(run, `PC Engine CD-ROM² · ${execution === 'worker' ? 'Worker' : 'Main'} execution`);
  try {
    const demoWav = makeDemoWav();
    signal.throwIfAborted();
    // PSG stays silent unless the edited script plays it. CD-DA / ADPCM share its audio output clock.
    const pg = Playground({
      chip: 'huc6280', pcEngineCd: true,
      logicWorkerUrl: runtimeAssetUrl('playground_logic_worker.js').href,
      readCddaFile: async path => {
        signal.throwIfAborted();
        if (path !== '/generated/bed.wav') throw new Error('Unknown demo audio path: ' + path);
        return demoWav;
      },
      onStatus(message) { report(run, message); },
      onLog(line) { report(run, line); },
    });
    run.runtime = pg;
    await pg.initialize();
    signal.throwIfAborted(); // Stop may have arrived while WASM was loading.
    pg.setMasterVolume(0.5);
    pg.load('pc-engine-cd-mix-01-three-sources', source);
    status.textContent = 'Playing…';
    await pg.play('pc-engine-cd-mix-01-three-sources', {execution});
    signal.throwIfAborted();
  } catch (error) {
    result = signal.aborted ? 'Stopped.' : `Error: ${error?.message ?? String(error)}`;
    if (!signal.aborted) report(run, result);
  } finally {
    try {
      // Initialization must settle before late-created audio can be closed.
      await run.runtime?.finalize();
    } catch (error) {
      result = `Cleanup error: ${error?.message ?? String(error)}`;
      report(run, result);
    } finally {
      run.runtime = null;
      if (activeRun === run) {
        activeRun = null;
        playButton.disabled = false;
        stopButton.disabled = true;
        executionSelect.disabled = false;
        status.textContent = result;
      }
    }
  }
});

function stop() {
  const run = activeRun;
  if (!run || run.controller.signal.aborted) return;
  run.controller.abort();
  stopButton.disabled = true;
  status.textContent = 'Stopping…';
  try { run.runtime?.stop(); }
  catch (error) { report(run, `Stop error: ${error?.message ?? String(error)}`); }
}
stopButton.addEventListener('click', stop);
window.addEventListener('pagehide', stop);
